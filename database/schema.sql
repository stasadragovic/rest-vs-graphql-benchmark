-- Ekstenzija za praćenje SQL upita (broj i trajanje upita po vrsti)
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

-- ---------------------------------------------------------------------
-- Korisnici
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    email       VARCHAR(255)  NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Projekti
-- ---------------------------------------------------------------------
CREATE TABLE projects (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(200)  NOT NULL,
    description  TEXT,
    owner_id     BIGINT        NOT NULL REFERENCES users (id),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Zadaci
-- ---------------------------------------------------------------------
CREATE TABLE tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    title        VARCHAR(200)  NOT NULL,
    description  TEXT,
    status       VARCHAR(20)   NOT NULL DEFAULT 'TODO'
                 CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    priority     SMALLINT      NOT NULL DEFAULT 2
                 CHECK (priority BETWEEN 1 AND 3),
    assignee_id  BIGINT        REFERENCES users (id),   -- zadatak ne mora biti dodeljen
    due_date     DATE,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Komentari
-- ---------------------------------------------------------------------
CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT        NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    author_id   BIGINT        NOT NULL REFERENCES users (id),
    text        TEXT          NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Indeksi
-- PostgreSQL NE pravi automatski indekse nad stranim ključevima.
-- Bez njih bi svaki upit tipa "zadaci projekta 42" pretraživao celu tabelu,
-- pa bismo u eksperimentu merili sporost baze, a ne razliku REST/GraphQL.
-- ---------------------------------------------------------------------
CREATE INDEX idx_projects_owner    ON projects (owner_id);
CREATE INDEX idx_tasks_project     ON tasks (project_id);
CREATE INDEX idx_tasks_assignee    ON tasks (assignee_id);
CREATE INDEX idx_comments_task     ON comments (task_id);
CREATE INDEX idx_comments_author   ON comments (author_id);